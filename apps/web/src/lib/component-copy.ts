export function componentFilterCopy(
  locale: InterfaceLanguage,
  english: string,
): string {
  if (locale !== "zh-CN") return english;
  const colon = english.indexOf(": ");
  if (colon < 0) return componentCopy(locale, english);
  const prefix = english.slice(0, colon);
  const known = new Set([
    "Search",
    "Result",
    "Market",
    "Source",
    "Bucket",
    "Status",
    "Position",
    "Popularity",
    "Difficulty",
    "Opportunity",
    "Country",
    "Tag",
    "Store",
    "Grade",
  ]);
  return known.has(prefix)
    ? `${componentCopy(locale, prefix)}：${english.slice(colon + 2)}`
    : componentCopy(locale, english);
}

export function componentCopy(
  locale: InterfaceLanguage,
  english: string,
): string {
  if (locale !== "zh-CN") return english;
  const normalized = english
    .trim()
    .replace(/\s+/g, " ")
    .replace(/\u2019/g, "’");
  if (copy[normalized] !== undefined) return copy[normalized];
  const translated = interfaceCopy(locale, normalized);
  return translated === normalized ? english : translated;
}
